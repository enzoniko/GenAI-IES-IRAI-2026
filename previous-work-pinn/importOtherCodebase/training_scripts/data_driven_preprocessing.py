def create_data_derived_scaling_params(data_path: str, device: torch.device = None) -> dict:
    """
    Create scaling parameters derived from the actual data range.
    This is a better fallback than identity transform as it uses the data's natural range.

    Args:
        data_path: Path to the X data file (will automatically find corresponding Y file)
        device: Device to place tensors on

    Returns:
        Dictionary with Xmin, Xmax, ymin, ymax tensors
    """
    if device is None:
        device = torch.device('cpu')

    # Load the data to compute actual min/max values
    X, y = load_pinn_data(data_path)

    # Compute scaling parameters from data
    # Flatten across rotation speeds and time to get global min/max per feature
    X_flat = X.reshape(-1, X.shape[-1])  # [total_samples, 10]
    y_flat = y.reshape(-1, y.shape[-1])  # [total_samples, 4]

    X_min = X_flat.min(dim=0)[0]  # Min across all samples for each feature
    X_max = X_flat.max(dim=0)[0]  # Max across all samples for each feature
    y_min = y_flat.min(dim=0)[0]  # Min across all samples for each output
    y_max = y_flat.max(dim=0)[0]  # Max across all samples for each output

    scaling_params = {
        'Xmin': X_min.double().to(device),
        'Xmax': X_max.double().to(device),
        'ymin': y_min.double().to(device),
        'ymax': y_max.double().to(device)
    }

    return scaling_params


def preprocess_data_driven_data(data_path: str, chunk_size_mb: int = 50) -> Dict[str, np.ndarray]:
    """
    Preprocess data using a trained data-driven model to extract residuals (maximum memory efficiency).

    Uses streaming processing to handle large datasets with minimal RAM usage.

    Args:
        data_path: Path to .pth data file (from LoadDatav3.py)
        chunk_size_mb: Target chunk size in MB (smaller = less RAM, slower processing)

    Returns:
        Dictionary containing 8 residual features:
        - data_res1, data_res2, data_res3, data_res4: Data residuals
        - phys_res1, phys_res2, phys_res3, phys_res4: Physics residuals (repeated data residuals)
    """
    log_memory_usage("Starting maximum memory efficiency preprocessing")

    # Force CPU usage for lower memory overhead
    device = torch.device('cpu')
    logger.debug("Using CPU device for maximum memory efficiency")

    # Load data-driven model and scaling parameters
    logger.info("Loading data-driven model")

    # Try to find the most recent data-driven model
    # Look in the parent directory's results folder (from josafat root)
    results_dir = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "results")
    data_driven_dirs = [d for d in os.listdir(results_dir) if d.startswith("data_driven_")]
    if not data_driven_dirs:
        raise FileNotFoundError(f"No data-driven model directories found in {results_dir}")

    # Get the most recent directory
    latest_dir = max(data_driven_dirs, key=lambda x: os.path.getctime(os.path.join(results_dir, x)))
    model_path = os.path.join(results_dir, latest_dir, "best_model.pth")

    if not os.path.exists(model_path):
        raise FileNotFoundError(f"Data-driven model file not found: {model_path}")

    logger.info(f"Using data-driven model from: {model_path}")
    logger.info(f"Available data-driven directories: {data_driven_dirs}")
    logger.info(f"Latest directory: {latest_dir}")

    model = load_data_driven_model(model_path, device)

    # Load scaling parameters
    try:
        scaling_params = load_scaling_params_from_data_driven(model_path)
    except FileNotFoundError:
        logger.warning("Scaling parameters not found for data-driven model, using data-derived normalization")
        # Create data-derived scaling parameters (much better than identity transform)
        scaling_params = create_data_derived_scaling_params(data_path, device)

    logger.info("Successfully loaded data-driven model")

    log_memory_usage("Model loaded")

    # Validate model predictions with a small sample
    validate_model_predictions(model, scaling_params, device)

    # Calculate total chunks for progress reporting
    # First load data to get dimensions, then clean up immediately
    X_temp, y_temp = load_pinn_data(data_path)
    total_samples = X_temp.shape[0] * X_temp.shape[1]
    bytes_per_sample = X_temp.element_size() * (X_temp.shape[2] + y_temp.shape[2])
    target_samples_per_chunk = (chunk_size_mb * 1024 * 1024) // bytes_per_sample
    total_chunks = (total_samples + target_samples_per_chunk - 1) // target_samples_per_chunk
    del X_temp, y_temp
    cleanup_memory()

    # Use streaming processing for maximum memory efficiency
    logger.debug(f"Using streaming processing with {chunk_size_mb}MB chunks ({total_chunks} total chunks)")

    # Collect all residuals
    all_residuals = {}
    residual_keys = ['data_res1', 'data_res2', 'data_res3', 'data_res4',
                    'phys_res1', 'phys_res2', 'phys_res3', 'phys_res4']

    # Initialize lists for each residual type
    for key in residual_keys:
        all_residuals[key] = []

    # Process in chunks with progress bar
    logger.info(f"Starting preprocessing with {total_chunks} chunks")
    data_iterator = load_pinn_data_chunked(data_path, chunk_size_mb)
    residuals_iterator = extract_data_driven_residuals_streaming(model, data_iterator, scaling_params, device, total_chunks)

    chunk_count = 0
    if HAS_TQDM:
        with tqdm(total=total_chunks, desc="Preprocessing data", unit="chunk") as overall_pbar:
            for chunk_residuals in residuals_iterator:
                chunk_count += 1
                logger.debug(f"Processed chunk {chunk_count}/{total_chunks}")
                # Accumulate residuals from this chunk
                for key in residual_keys:
                    all_residuals[key].append(chunk_residuals[key])
                overall_pbar.update(1)
    else:
        # Fallback without progress bar
        for chunk_residuals in residuals_iterator:
            chunk_count += 1
            logger.debug(f"Processed chunk {chunk_count}/{total_chunks}")
            # Accumulate residuals from this chunk
            for key in residual_keys:
                all_residuals[key].append(chunk_residuals[key])

    logger.info(f"Processed {chunk_count} chunks total")

    # Concatenate all chunks
    log_memory_usage("Concatenating streaming results")
    final_residuals = {}
    for key in residual_keys:
        final_residuals[key] = np.concatenate(all_residuals[key], axis=0)

    # Clean up
    del all_residuals
    cleanup_memory()

    log_memory_usage("Maximum memory efficiency preprocessing completed")
    return final_residuals


def get_residual_features(residuals_dict: Dict[str, np.ndarray]) -> np.ndarray:
    """
    Convert residuals dictionary to feature matrix for machine learning.

    Args:
        residuals_dict: Dictionary from preprocess_data_driven_data

    Returns:
        Feature matrix of shape [num_samples, 8]
    """
    features = np.column_stack([
        residuals_dict['data_res1'], residuals_dict['data_res2'],
        residuals_dict['data_res3'], residuals_dict['data_res4'],
        residuals_dict['phys_res1'], residuals_dict['phys_res2'],
        residuals_dict['phys_res3'], residuals_dict['phys_res4']
    ])
    return features


def get_rotation_speed_separated_features(data_path: str, chunk_size_mb: int = 50) -> np.ndarray:
    """
    Get features separated by rotation speed: [n_rotation_speeds, n_timestamps_per_speed, 8]

    Args:
        data_path: Path to .pth file from LoadDatav3.py
        chunk_size_mb: Target chunk size in MB for streaming processing

    Returns:
        Array of shape [n_rotation_speeds, n_timestamps_per_speed, 8]
    """
    log_memory_usage("Starting rotation speed separated features")

    # Load raw data to get dimensions
    X, y = load_pinn_data(data_path)
    n_rotation_speeds, n_timestamps_per_speed = X.shape[0], X.shape[1]
    log_memory_usage(f"Data shape: {X.shape}")

    # Clean up the initial data load immediately
    del X, y
    cleanup_memory()

    # Get residuals using preprocessing
    residuals = preprocess_data_driven_data(data_path, chunk_size_mb)

    # Convert to feature matrix
    features_flat = get_residual_features(residuals)  # [total_samples, 8]

    # Reshape back to separated format
    features_separated = features_flat.reshape(
        n_rotation_speeds,
        n_timestamps_per_speed,
        8
    )

    # Clean up
    del residuals, features_flat
    cleanup_memory()

    log_memory_usage("Rotation speed separated features completed")
    return features_separated


