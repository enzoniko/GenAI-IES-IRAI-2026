"""
Data-Driven Residuals Preprocessor (Memory Optimized)

This module provides functions to extract residuals from trained data-driven models
for use as features in other experiments. It loads data from .pth files
generated by LoadDatav3.py and returns residuals in memory.

This version repeats data residuals as physics residuals to maintain compatibility
with downstream analysis tools that expect 8 residual features.

Memory optimizations:
- Batch processing to avoid loading entire datasets
- Memory cleanup with explicit garbage collection
- Optional memory mapping for large files
- Streaming processing for large datasets
"""

